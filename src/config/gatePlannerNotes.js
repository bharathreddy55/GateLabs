const byTopic = new Map(Object.entries(topicsByNote).flatMap(([note, topics]) =>
  topics.map(topic => [topic, [note]])
));

export function gatePlannerNoteIds(subject, topic) {
  if (topic === 'Performance Metrics' && subject.endsWith('Computer Networks')) return ['network-performance'];
  if (topic === 'IPv4: Fragmentation, CIDR Notation, NAT') return ['ipv4-fragmentation', 'cidr-nat'];
  return byTopic.get(topic) || [];
}
